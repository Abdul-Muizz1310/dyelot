/** Each row as a frozen entry of its category, its set and hues frozen too. */
function entries(category: LexiconCategory, rows: readonly Row[]): LexiconEntry[] {
  return rows.map(([term, weight, set]) =>
    Object.freeze({
      term,
      category,
      weight,
      set: Object.freeze(
        set.hues === undefined ? { ...set } : { ...set, hues: Object.freeze({ ...set.hues }) },
      ),
    }),
  );
}

