// The lexicon's data (docs/specs/04-ai.md, R4-42 and sections 7.1 to 7.3): the words a brief may use,
// each mapped to the design parameters it reads as. When no model answers, this table is the brief
// feature, so every mapping is a reading a designer can defend. Its sources are dyelot's own:
//
// - The preset table (src/engine/presets.ts): a style that names a preset votes for it, and a word
//   the preset's summary describes ("Earth tones, round corners" for organic, "Loud triads" for
//   neo-brutalism) takes the preset's values.
// - The pairings' fit column (src/engine/fonts/pairings.ts): Swiss and dev-tool vote host-grotesk,
//   editorial schibsted-serif, luxury gloock-albert, organic and food young-onest, fashion
//   bodoni-familjen, docs and reading literata-spline, tech hubot-mona, startup funnel, e-commerce
//   zalando, retro-futurism unbounded-golos, zine archivo-courier, sports and industrial
//   shoulders-redhat, pixel tiny5-spline, retro-tech and dashboards doto-redhat, grain and anti-design
//   redaction-redhat, calm commissioner, accessible and health atkinson, expressive google-flex,
//   kinetic anybody-albert, sci-fi and HUD science-hanken. The vibe's type table (TYPE_VIBE_PAIRING)
//   gives the type words: geometric, humanist, grotesk, serif and monospace.
// - The warm and cool hue rule of 04-color-science (R3-29): a set with a warm or cool tint and a
//   primary hue keeps them on the same side, warm in [0, 140) or [330, 360), cool in [140, 330).
//
// The rules the data follows:
//
// - A hue only where the word has a color of its own: a color name, a pigment, a gem, a material, a
//   landscape, a time of day. Hues are OKLCH angles (red 29, orange 55, yellow 100, green 145, teal
//   190, blue 260, violet 295, magenta 330). A word for a feeling sets no hue, because hues average:
//   "warm blue" must stay blue, so "warm" sets only the tint.
// - A color name sets only its hue, and a muted chroma when the name means one (brown, mustard). A
//   material, place or gem adds the tint its surfaces suggest (terracotta warm, steel cool).
// - Weight 3: the word names a parameter or a style outright (a preset, a pairing's fit word, a color,
//   "monochrome", "dense"), or a strong image (tea house). Weight 2: a clear association. Weight 1: a
//   loose one, or a word with other common senses (data, modern, cloud).
// - The order is the tie-break (7.4): styles first, then moods, industries, eras, materials and
//   places, so an explicit style word wins a tie over a loose image.
// - No brand or company name (7.3), and no term that is another's suffix form, so a word matches at
//   most one term. Terms are copy ("Matched: tea house, dusk, calm"), so American English (gray,
//   theater, jewelry).

type Weight = LexiconEntry["weight"];
type LexiconSet = Omit<BriefDraft, "name" | "oneLiner" | "adjectives">;
type Row = readonly [term: string, weight: Weight, set: LexiconSet];

